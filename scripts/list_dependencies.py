"""Write docs/DEPENDENCIES.md: every direct and transitive dependency with its licence.

Python: the closure of backend/requirements.txt (and the -r files it includes),
read from the installed package metadata of the backend venv.
Frontend: frontend/package-lock.json; runtime packages (shipped in the app)
and build/dev tools are listed separately.

Run with the backend venv so the metadata is the installed one:
    backend/.venv/Scripts/python scripts/list_dependencies.py
"""

from __future__ import annotations

import json
import re
from datetime import date
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def top_level(req_file: Path) -> list[Requirement]:
    reqs = []
    for line in req_file.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("-r"):
            reqs += top_level(req_file.parent / line[2:].strip())
        else:
            reqs.append(Requirement(line))
    return reqs


def licence_of(dist: metadata.Distribution) -> str:
    m = dist.metadata
    expr = m.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split(" :: ")[-1] for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(classifiers)
    lic = (m.get("License") or "").strip()
    return lic.splitlines()[0][:60] if lic else "unknown"


def python_closure() -> dict[str, tuple[str, str, bool]]:
    direct = top_level(ROOT / "backend" / "requirements.txt")
    out: dict[str, tuple[str, str, bool]] = {}
    queue = [(r, True) for r in direct]
    while queue:
        req, is_direct = queue.pop()
        key = norm(req.name)
        if key in out:
            if is_direct and not out[key][2]:
                out[key] = (*out[key][:2], True)
            continue
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            continue  # e.g. a platform-specific extra not installed here
        out[key] = (dist.version, licence_of(dist), is_direct)
        env = {"extra": ""}
        for spec in dist.requires or []:
            sub = Requirement(spec)
            extras_ok = sub.marker is None or sub.marker.evaluate(env) or any(
                sub.marker.evaluate({"extra": e}) for e in req.extras)
            if extras_ok:
                queue.append((sub, False))
    return dict(sorted(out.items()))


def npm_packages() -> tuple[list, list]:
    lock = json.loads((ROOT / "frontend" / "package-lock.json").read_text(encoding="utf-8"))
    pkg = json.loads((ROOT / "frontend" / "package.json").read_text(encoding="utf-8"))
    direct = set(pkg.get("dependencies", {})) | set(pkg.get("devDependencies", {}))
    runtime, dev = {}, {}
    for path, v in lock["packages"].items():
        if not path:
            continue
        name = path.split("node_modules/")[-1]
        row = (v.get("version", "?"), v.get("license", "unknown"), name in direct)
        (dev if v.get("dev") else runtime)[name] = row
    return sorted(runtime.items()), sorted(dev.items())


def table(rows) -> str:
    lines = ["| Package | Version | Licence | Direct |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {lic} | {'yes' if d else ''} |" for n, (v, lic, d) in rows]
    return "\n".join(lines)


def main() -> None:
    py = python_closure()
    rt, dev = npm_packages()
    text = f"""# Dependencies (generated)

Generated by `scripts/list_dependencies.py` on {date.today().isoformat()}; do not edit by hand.
Direct dependencies with their purpose are in `CREDITS.md`.

## Backend (Python, closure of `backend/requirements.txt`): {len(py)} packages

{table(py.items())}

## Frontend runtime (shipped in the app): {len(rt)} packages

{table(rt)}

## Frontend build and development tools (not shipped): {len(dev)} packages

{table(dev)}
"""
    (ROOT / "docs" / "DEPENDENCIES.md").write_text(text, encoding="utf-8")
    licences = sorted({lic for _, (_, lic, _) in [*py.items(), *rt, *dev]})
    print(f"python {len(py)}, npm runtime {len(rt)}, npm dev {len(dev)}")
    print("licences:", licences)


if __name__ == "__main__":
    main()
